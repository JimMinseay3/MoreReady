'use strict';
const assert = require('node:assert/strict');
const Keys = require('../src/renderer/shortcuts');
const W = require('../src/renderer/ai-workflow');
const task = (id, deps = [], projectId = 'p') => ({ id, projectId, title: id, notes: '', status: 'todo', priority: 'p2', due: '', subtasks: [], dependsOn: deps });
const state = { projects: [{ id: 'p', name: '交付', desc: '' }, { id: 'q', name: '其他项目' }], tasks: [task('a'), task('b', ['a']), task('z', [], 'q')] };
const context = W.contextFrom(state, 'p', 'a', '2026-10-06');
const request = mode => ({ mode, goal: '', context });
const empty = () => ({ summary: '建议先确认验收标准', advice: [], tasks: [], subtasks: [], links: [] });
const plan = { ...empty(), tasks: [
  { key: 'new-1', title: '验证接口', notes: '检查返回数据', due: '', priority: 'p1', dependsOn: ['a'] },
  { key: 'new-2', title: '联调页面', notes: '', due: '2026-10-12', priority: 'p2', dependsOn: ['new-1'] },
] };
let sequence = 0;
const normalized = W.validatePlan(plan, request('project-plan'));
const before = JSON.stringify(state);
assert.throws(() => W.prepare(state, request('project-plan'), normalized, ['task:1'], { uid: () => 'id' + ++sequence }), /一并勾选/);
assert.equal(JSON.stringify(state), before, 'validation must not partially mutate original tasks');
const prepared = W.prepare(state, request('project-plan'), normalized, ['task:0', 'task:1'], { uid: () => 'id' + ++sequence });
assert.equal(prepared.tasks.length, 5);
const first = prepared.tasks.find(t => t.title === '验证接口'), second = prepared.tasks.find(t => t.title === '联调页面');
assert.deepEqual(second.dependsOn, [first.id]); assert.deepEqual(first.dependsOn, ['a']);
assert.equal(prepared.tasks.find(t => t.id === 'z').projectId, 'q');
assert.equal(JSON.stringify(state), before);
assert.throws(() => W.validatePlan({ ...empty(), links: [{ from: 'b', to: 'a', reason: '前置' }] }, request('dependencies')), /循环/);
assert.throws(() => W.validatePlan({ ...empty(), links: [{ from: 'z', to: 'a', reason: '其他项目' }] }, request('dependencies')), /所选项目/);
assert.throws(() => W.validatePlan({ ...empty(), links: [{ from: 'a', to: 'b', reason: '已有' }] }, request('dependencies')), /重复/);
assert.throws(() => W.validatePlan({ ...empty(), subtasks: [{ title: '检查' }] }, request('review')), /不支持/);
assert.throws(() => W.validatePlan({ ...empty(), deleteTasks: ['a'] }, request('review')), /不支持/);
assert.throws(() => W.validatePlan({ ...plan, tasks: [{ ...plan.tasks[0], due: '2026-02-30' }] }, request('project-plan')), /日期/);
assert.throws(() => W.validatePlan({ ...plan, tasks: [{ ...plan.tasks[0], dependsOn: ['unknown'] }] }, request('project-plan')), /不存在|不可用/);
assert.throws(() => W.normalizeRequest({ mode: 'toString', context }), /工作方式/);
assert.throws(() => W.normalizeRequest({ mode: 'task-breakdown', context: { ...context, taskId: '' } }), /选择/);
assert.throws(() => W.parse('{"summary":"broken"'), /未返回/);
assert.deepEqual(W.parse('```json\n' + JSON.stringify(empty()) + '\n```'), empty());
const subtasks = W.prepare(state, request('task-breakdown'), { ...empty(), subtasks: [{ title: '核对验收标准' }] }, ['sub:0'], { uid: () => 'sub-id' });
assert.equal(subtasks.tasks.find(t => t.id === 'a').subtasks[0].title, '核对验收标准');
const defaults = Keys.normalize();
assert.equal(defaults.previousPage.mouse, 3); assert.equal(defaults.nextPage.mouse, 4);
assert.equal(Keys.keyboard({ code: 'KeyN' }), null); assert.equal(Keys.keyboard({ code: 'Space', ctrl: true, shift: true }), null);
assert.ok(Keys.keyboard({ code: 'F8' })); assert.equal(Keys.keyboard({ code: '<script>' }), null);
const changed = Keys.assign(defaults, 'toggleAI', 'keyboard', defaults.search.keyboard);
assert.equal(changed.search.keyboard, null); assert.equal(changed.toggleAI.keyboard.code, 'KeyF');
const mouse = Keys.assign(defaults, 'save', 'mouse', 3);
assert.equal(mouse.previousPage.mouse, null); assert.equal(mouse.save.mouse, 3);
assert.deepEqual(Keys.normalize(JSON.parse(JSON.stringify(mouse))), mouse);
assert.equal(Keys.normalize({ save: { keyboard: null, mouse: null } }).save.keyboard, null);
assert.equal(Keys.format(Keys.keyboard({ code: 'KeyA', ctrl: true, shift: true })), 'Ctrl + Shift + A');
console.log('PASS workflow validation: selection prerequisites, atomic plans, same-project acyclic dependencies, schema/date checks, subtask creation and shortcut conflict/persistence rules');
